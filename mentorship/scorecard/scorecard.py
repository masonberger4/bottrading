"""Conflict scorecard: tally how many separate ICT videos support each position on each
rule conflict, and render SCORECARD.md + summary.csv.

Run from the repo root:
    python mentorship/scorecard/build_lectures.py   # only when new notes were added
    python mentorship/scorecard/scorecard.py

Data (append new batches here; see README.md):
    conflicts.csv  id, topic, question, in_force, digest_refs
    positions.csv  conflict, pos, position
    evidence.csv   conflict, pos, lecture, quote, ts      (one row = one video supporting one position)
    lectures.csv   built from the note headers (key, playlist, video id, date, ...)

The script never picks a winner. It counts distinct videos (the same YouTube video listed in
two playlists counts once), and shows the 2023 Mentorship count and the newest date separately,
so the 2023-beats-older rule and recency can be read side by side.
"""
import csv, pathlib, sys, collections

HERE = pathlib.Path(__file__).resolve().parent
PLAYLISTS = [  # code, label, short
    ("M2023", "2023 Mentorship", "2023"),
    ("CC", "2016-17 Core Content", "CC"),
    ("CH", "Charter (2018-22)", "Charter"),
    ("TE", "Trade Executions (2023-26)", "TE"),
    ("M2024", "2024 Mentorship", "2024"),
    ("L2025", "2025 Lectures", "2025"),
    ("SMC2026", "2026 SMC Lectures", "2026"),
]
LABEL = {c: l for c, l, _ in PLAYLISTS}
SHORT = {c: s for c, _, s in PLAYLISTS}
ORDER = {c: i for i, (c, _, _) in enumerate(PLAYLISTS)}
TOPIC_ORDER = ["Times", "Opening range", "Opening gaps", "News", "Day filters", "Weekly profile",
               "PD arrays", "Levels", "Bias and SMT", "Management", "Data"]  # new topics go last


def read(name):
    with (HERE / name).open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def load():
    lectures = {r["key"]: r for r in read("lectures.csv")}
    conflicts = read("conflicts.csv")
    positions = read("positions.csv")
    evidence = read("evidence.csv")
    errors = []
    cids = [c["id"] for c in conflicts]
    dup = [c for c, n in collections.Counter(cids).items() if n > 1]
    if dup:
        errors.append(f"duplicate conflict ids: {dup}")
    pos_keys = set()
    for p in positions:
        if p["conflict"] not in cids:
            errors.append(f"positions.csv: unknown conflict {p['conflict']}")
        k = (p["conflict"], p["pos"])
        if k in pos_keys:
            errors.append(f"positions.csv: duplicate position {k}")
        pos_keys.add(k)
    for i, e in enumerate(evidence, start=2):
        if (e["conflict"], e["pos"]) not in pos_keys:
            errors.append(f"evidence.csv line {i}: unknown position {e['conflict']}/{e['pos']}")
        if e["lecture"] not in lectures:
            errors.append(f"evidence.csv line {i}: unknown lecture {e['lecture']} (run build_lectures.py?)")
    dmap = read("digest_map.csv") if (HERE / "digest_map.csv").exists() else []
    for r in dmap:
        for cid in r["scorecard"].split():
            if cid not in cids:
                errors.append(f"digest_map.csv: {r['digest']} #{r['num']} -> unknown conflict {cid}")
    if errors:
        sys.exit("\n".join(errors))
    return lectures, conflicts, positions, evidence, dmap


def tally(rows, lectures):
    """rows = evidence rows for one position -> stats dict."""
    vids = {}  # video identity -> list of lecture keys
    for e in rows:
        lec = lectures[e["lecture"]]
        vid = lec["video_id"] or lec["key"]
        vids.setdefault(vid, []).append(lec)
    by_pl = collections.Counter()
    for lecs in vids.values():
        # a shared video counts once overall, credited to its highest-tier playlist
        best = min(lecs, key=lambda l: ORDER[l["playlist"]])
        by_pl[best["playlist"]] += 1
    dates = [l["date"] for lecs in vids.values() for l in lecs if l["date"]]
    return {
        "videos": len(vids),
        "m2023": by_pl.get("M2023", 0),
        "by_pl": by_pl,
        "newest": max(dates) if dates else "",
        "oldest": min(dates) if dates else "",
    }


def fmt_pl(by_pl):
    return ", ".join(f"{SHORT[c]} {n}" for c, n in sorted(by_pl.items(), key=lambda x: ORDER[x[0]]))


def lec_label(lec):
    d = f" ({lec['date']})" if lec["date"] else ""
    return f"{LABEL[lec['playlist']]} {lec['lecture']}{d}"


def main():
    lectures, conflicts, positions, evidence, dmap = load()
    pos_by_c = collections.defaultdict(list)
    for p in positions:
        pos_by_c[p["conflict"]].append(p)
    ev_by_p = collections.defaultdict(list)
    for e in evidence:
        ev_by_p[(e["conflict"], e["pos"])].append(e)

    summary, md = [], []
    md.append("# Rule conflict scorecard (DRAFT, aid for Mase's full review)\n")
    md.append("Generated by `mentorship/scorecard/scorecard.py` from the CSVs in this folder; "
              "do not edit by hand. Read `README.md` for how counts work.\n")
    md.append("**Videos** = separate ICT videos supporting the position (a video in two playlists "
              "counts once). **2023** = how many of those are 2023 Mentorship (the tier that wins "
              "conflicts). **By playlist** splits the count. **Newest** = latest dated video. "
              "Nothing here picks a winner or changes the engine.\n")
    n_c = len(conflicts)
    n_v = len({(lectures[e['lecture']]['video_id'] or e['lecture']) for e in evidence})
    md.append(f"{n_c} conflicts, {len(positions)} positions, {len(evidence)} evidence rows "
              f"from {n_v} separate videos.\n")

    # summary table
    md.append("## Summary\n")
    md.append("| Conflict | Question | Most videos | Most 2023 videos | Newest support |")
    md.append("|---|---|---|---|---|")
    detail = []
    topic_order = [t for t in TOPIC_ORDER if any(c["topic"] == t for c in conflicts)]
    for c in conflicts:
        if c["topic"] not in topic_order:
            topic_order.append(c["topic"])
    for topic in topic_order:
        for c in [c for c in conflicts if c["topic"] == topic]:
            stats = {p["pos"]: tally(ev_by_p[(c["id"], p["pos"])], lectures) for p in pos_by_c[c["id"]]}
            ptext = {p["pos"]: p["position"] for p in pos_by_c[c["id"]]}

            def lead(key):
                best = max(stats.values(), key=lambda s: s[key]) if stats else None
                if not best or best[key] == 0:
                    return "none"
                tops = [k for k, s in stats.items() if s[key] == best[key]]
                if len(tops) > 1:
                    return f"tie {'/'.join(tops)} ({best[key]} each)"
                t = ptext[tops[0]]
                return f"**{tops[0]}** ({best[key]}): {t[:60] + '...' if len(t) > 60 else t}"
            newest = max(stats.items(), key=lambda kv: kv[1]["newest"]) if stats else None
            newest_s = f"{newest[0]} ({newest[1]['newest'][:7]})" if newest and newest[1]["newest"] else "none"
            anchor = c["id"].lower()
            md.append(f"| [{c['id']}](#{anchor}) | {c['question']} | {lead('videos')} | {lead('m2023')} | {newest_s} |")
            for p in pos_by_c[c["id"]]:
                s = stats[p["pos"]]
                summary.append({"conflict": c["id"], "topic": topic, "pos": p["pos"],
                                "position": p["position"], "videos": s["videos"], "m2023": s["m2023"],
                                "by_playlist": fmt_pl(s["by_pl"]), "oldest": s["oldest"], "newest": s["newest"]})
            # detail block
            detail.append(f"### {c['id']}\n")
            detail.append(f"**{c['question']}**\n")
            detail.append(f"- In force now: {c['in_force']}")
            detail.append(f"- Digest conflicts merged here: {c['digest_refs']}\n")
            detail.append("| Pos | Position | Videos | 2023 | By playlist | Newest |")
            detail.append("|---|---|---|---|---|---|")
            for p in sorted(pos_by_c[c["id"]], key=lambda p: -stats[p["pos"]]["videos"]):
                s = stats[p["pos"]]
                detail.append(f"| {p['pos']} | {p['position']} | {s['videos']} | {s['m2023']} | "
                              f"{fmt_pl(s['by_pl']) or '-'} | {s['newest'] or '-'} |")
            detail.append("")
            for p in pos_by_c[c["id"]]:
                rows = ev_by_p[(c["id"], p["pos"])]
                detail.append(f"**{p['pos']}. {p['position']}**")
                if not rows:
                    detail.append("- (no lecture evidence collected; rulebook/engine default only)")
                for e in sorted(rows, key=lambda e: (ORDER[lectures[e['lecture']]['playlist']], lectures[e['lecture']]['date'], e['lecture'])):
                    lec = lectures[e["lecture"]]
                    ts = f" {e['ts']}" if e["ts"] else ""
                    detail.append(f"- {lec_label(lec)}{ts}: {e['quote']}  \n  `{lec['note']}`")
                detail.append("")
    md.append("")
    # re-emit details grouped by topic headers
    by_topic = collections.OrderedDict((t, []) for t in topic_order)
    cur = None
    for line in detail:
        if line.startswith("### "):
            cid = line[4:].strip()
            cur = next(c["topic"] for c in conflicts if c["id"] == cid)
        if cur:
            by_topic[cur].append(line)
    for t, lines in by_topic.items():
        md.append(f"## {t}\n")
        md.extend(lines)
    if dmap:
        md.append("## Coverage of the digest conflict lists\n")
        per = collections.Counter(r["digest"] for r in dmap)
        scored = collections.Counter(r["digest"] for r in dmap if r["scorecard"])
        md.append("| Digest | Conflicts listed | Merged into a card | Not scored |")
        md.append("|---|---|---|---|")
        for d in per:
            md.append(f"| `{d}_draft_rules.md` (+ batches) | {per[d]} | {scored[d]} | {per[d] - scored[d]} |")
        md.append("\nWhere each digest conflict went is in `digest_map.csv`. Not scored, with the reason:\n")
        for r in dmap:
            if not r["scorecard"]:
                md.append(f"- {r['digest']} #{r['num']}: {r['note']}")
        notes = [r for r in dmap if r["scorecard"] and r["note"]]
        if notes:
            md.append("\nNotes on merged items:\n")
            for r in notes:
                md.append(f"- {r['digest']} #{r['num']} ({r['scorecard']}): {r['note']}")
        md.append("")
    (HERE / "SCORECARD.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    with (HERE / "summary.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, list(summary[0].keys()))
        w.writeheader()
        w.writerows(summary)
    print(f"{n_c} conflicts, {len(positions)} positions, {len(evidence)} rows, {n_v} videos -> SCORECARD.md, summary.csv")


if __name__ == "__main__":
    main()
