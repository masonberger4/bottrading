"""Owner rule (Mase 2026-11-06): on every card the position backed by the most
distinct videos is the default; every other position is a switch. Earlier owner
answers are superseded. Ties go to Mase (2026-11-07): set TIE_PICKS.
Reads summary.csv (run scorecard.py first); writes defaults.csv and DEFAULTS.md.
Rules stay DRAFT: this records defaults, it does not change the engine."""
import csv, collections, os
H = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(H, 'summary.csv'), encoding='utf-8')))
cards = collections.OrderedDict()
for r in rows:
    cards.setdefault(r['conflict'], []).append(r)
# Mase 2026-11-06: where ICT gives a beginner and an experienced version, the experienced one is
# the default whatever the count. Cards where that changes the count winner:
EXPERIENCED = {'NFP-THU-FRI': 'B'}
# Mase 2026-11-07: ties on video count go to Mase; no automatic tie-break.
# Fill in his pick here as {card: pos}; until then the card shows PENDING.
TIE_PICKS = {}
key = lambda r: (int(r['videos']), int(r['m2023']), r['newest'] or '')
out = []
for c, ps in cards.items():
    ranked = sorted(ps, key=key, reverse=True)
    flags = []
    if c in EXPERIENCED:
        ranked = [p for p in ranked if p['pos'] == EXPERIENCED[c]] + [p for p in ranked if p['pos'] != EXPERIENCED[c]]
        flags.append('experienced version (overrides count)')
    win, second = ranked[0], ranked[1] if len(ranked) > 1 else None
    if flags:
        pass
    elif second and win['videos'] == second['videos']:
        tied = [p for p in ranked if p['videos'] == win['videos']]
        if c in TIE_PICKS:
            ranked = [p for p in ranked if p['pos'] == TIE_PICKS[c]] + [p for p in ranked if p['pos'] != TIE_PICKS[c]]
            win = ranked[0]; flags.append('tie: Mase picked')
        else:
            flags.append('TIE PENDING Mase: ' + '/'.join(p['pos'] for p in tied))
    elif second and int(win['videos']) - int(second['videos']) == 1:
        flags.append('margin 1')
    if int(win['videos']) <= 2:
        flags.append('thin (<=2 videos)')
    out.append(dict(conflict=c, topic=win['topic'], default=win['pos'], videos=win['videos'],
                    position=win['position'],
                    switches=' '.join(f"{p['pos']}({p['videos']})" for p in ranked[1:]),
                    flags='; '.join(flags)))
with open(os.path.join(H, 'defaults.csv'), 'w', newline='', encoding='utf-8') as f:
    w = csv.DictWriter(f, fieldnames=list(out[0])); w.writeheader(); w.writerows(out)
md = ['# Defaults by count (DRAFT)', '',
      'Owner rule (Mase, 2026-11-06): the position with the most distinct videos is the default; every other',
      'position is a switch (off). Earlier owner answers are superseded by the count. Ties go to Mase',
      '(2026-11-07); a pending tie lists the first tied position until he picks. Generated by `defaults.py` from `summary.csv`; flagged rows are',
      'the ones put to Mase for a second look. Nothing here changes the engine yet.',
      'Where ICT labels a beginner vs experienced version, the experienced one is default regardless of count.', '']
topic = None
for o in out:
    if o['topic'] != topic:
        topic = o['topic']; md += ['', f'## {topic}', '', '| Card | Default | Videos | Switches | Flag |', '|---|---|---|---|---|']
    md.append(f"| {o['conflict']} | **{o['default']}**: {o['position'].replace('|','/')} | {o['videos']} | {o['switches']} | {o['flags']} |")
open(os.path.join(H, 'DEFAULTS.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
print(len(out), 'cards;', sum(1 for o in out if o['flags']), 'flagged')

# One-source rules (singles.csv, built by singles.py)
import subprocess, sys
subprocess.run([sys.executable, os.path.join(H, 'singles.py')], check=True)
s = list(csv.DictReader(open(os.path.join(H, 'singles.csv'), encoding='utf-8')))
md2 = ['', '## One-source rules', '',
       'Mase 2026-11-06: one video beats an engine default no video supports, so these become DRAFT defaults',
       '(the current engine behaviour is the switch), except rows marked excluded.', '',
       '| Digest | # | Status | Rule | Why |', '|---|---|---|---|---|']
md2 += [f"| {r['digest']} | {r['num']} | {r['status']} | {r['rule'].replace('|','/')} | {r['reason'].replace('|','/')} |" for r in s]
open(os.path.join(H, 'DEFAULTS.md'), 'a', encoding='utf-8').write('\n'.join(md2) + '\n')
